#!/usr/bin/env bash
# Fetches and trims llama.cpp into core/src/main/cpp/llama.cpp.
#
# Why this is a script and not a submodule: the full tree is ~230 MB / 4,000 files, and the
# build only needs ~33 MB of it. Trimming keeps clones and archives small; pinning keeps the
# C++ API stable (llama.cpp changes its public API often).
#
# Usage:  ./scripts/fetch_llama.sh            # download pinned zip (needs curl+unzip)
#         USE_GIT=1 ./scripts/fetch_llama.sh  # clone instead (needs git)
set -euo pipefail

PINNED_COMMIT="918076a6354c647304c33ca12ee71f80de1c91ae"
REPO="https://github.com/ggml-org/llama.cpp"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/core/src/main/cpp/llama.cpp"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

if [ -d "$DEST" ] && [ -f "$DEST/CMakeLists.txt" ]; then
  echo "llama.cpp already present at $DEST — delete it first if you want to re-fetch."
  exit 0
fi

echo "==> fetching llama.cpp @ $PINNED_COMMIT"
if [ "${USE_GIT:-0}" = "1" ]; then
  git clone --depth 1 "$REPO" "$TMP/src"
  ( cd "$TMP/src" && { git checkout -q "$PINNED_COMMIT" 2>/dev/null \
      || git fetch -q --depth 1 origin "$PINNED_COMMIT" && git checkout -q "$PINNED_COMMIT"; } ) \
    || echo "!! could not check out the pinned commit; staying on default branch HEAD"
else
  curl -fsSL "$REPO/archive/$PINNED_COMMIT.zip" -o "$TMP/src.zip"
  unzip -q "$TMP/src.zip" -d "$TMP"
  mv "$TMP"/llama.cpp-* "$TMP/src"
fi

echo "==> trimming (dropping examples, tests, tools, GPU backends we do not build)"
# Keep: CMakeLists.txt, cmake/, common/, vendor/, include/, src/ (incl. src/models/),
#       ggml/{CMakeLists.txt,cmake/,include/,src/} with ggml-cpu + ggml-vulkan only.
rm -rf \
  "$TMP/src/examples" "$TMP/src/tests" "$TMP/src/tools" "$TMP/src/docs" "$TMP/src/models" \
  "$TMP/src/benches" "$TMP/src/pocs" "$TMP/src/media" "$TMP/src/ci" "$TMP/src/scripts" \
  "$TMP/src/gguf-py" "$TMP/src/conversion" "$TMP/src/requirements" "$TMP/src/app" \
  "$TMP/src/ui" "$TMP/src/skills" "$TMP/src/.git" "$TMP/src/grammars" "$TMP/src/licenses" \
  "$TMP/src/ggml/src/ggml-cuda" "$TMP/src/ggml/src/ggml-sycl" "$TMP/src/ggml/src/ggml-metal" \
  "$TMP/src/ggml/src/ggml-cann" "$TMP/src/ggml/src/ggml-hexagon" "$TMP/src/ggml/src/ggml-webgpu" \
  "$TMP/src/ggml/src/ggml-openvino" "$TMP/src/ggml/src/ggml-et" "$TMP/src/ggml/src/ggml-opencl"

mkdir -p "$(dirname "$DEST")"
mv "$TMP/src" "$DEST"

if [ ! -f "$DEST/CMakeLists.txt" ] || [ ! -d "$DEST/ggml/src/ggml-cpu" ]; then
  echo "!! trim looks wrong: required sources are missing" >&2
  exit 1
fi

# Vulkan builds only: make ggml's shader generator emit SPIR-V as string literals.
#
# Upstream writes one "0xAB," per byte, which is ~13.5 M initializer expressions in
# mul_mm.comp.cpp alone. clang needs ~1.5 GB RSS to parse that single TU and is OOM-killed on
# machines with under ~2 GB free. The patch is byte-identical output, ~774 MB peak. Skipped
# harmlessly when the file is absent (e.g. an already-patched tree).
if [ -f "$ROOT/patches/0001-vulkan-shaders-gen-string-literals.patch" ] && \
   [ -f "$DEST/ggml/src/ggml-vulkan/vulkan-shaders/vulkan-shaders-gen.cpp" ]; then
  if ( cd "$DEST" && patch -p1 -s --forward --dry-run \
        < "$ROOT/patches/0001-vulkan-shaders-gen-string-literals.patch" >/dev/null 2>&1 ); then
    ( cd "$DEST" && patch -p1 -s --forward \
        < "$ROOT/patches/0001-vulkan-shaders-gen-string-literals.patch" )
    echo "==> applied Vulkan shader-generator patch (low-RAM shader embedding)"
  else
    echo "==> Vulkan shader-generator patch already applied or not applicable — skipping"
  fi
fi

cat > "$DEST/VENDORED.md" <<'EOF'
# Vendored llama.cpp (fetched, not committed)

- Upstream: https://github.com/ggml-org/llama.cpp
- Pinned commit: 918076a6354c647304c33ca12ee71f80de1c91ae
- Generated by scripts/fetch_llama.sh — do not commit this directory.

The JNI bridge and engine are written against this exact revision's API:
`llama_batch_ext` + `llama_process(LLAMA_PROCESS_TYPE_DECODE)`, `llama_load_mode`
instead of `use_mmap`/`use_mlock` booleans, and `llama_memory_seq_pos_max()`.
EOF

echo "==> done: $(du -sh "$DEST" | cut -f1) at $DEST"
echo "    measured size after this exact trim: ~33 MB / ~1,270 files"
