#!/usr/bin/env python3
"""
Generates Compose screen stubs for the MainActivity type-check pass.

WHY
    The main type-check has to compile every real file, but the screen composables need the Compose
    compiler plugin, which bare kotlinc cannot apply. The first version of the script solved this by
    stubbing *MainActivity* instead — and MainActivity went out with five compile errors that the
    gate could not see, because the file was excluded from the check.

    So the stubs are generated from the real files here. If a screen's parameters change, the stub
    changes with it automatically, and MainActivity is always checked against the true signature.

USAGE
    python3 tools/gen_screen_stubs.py <out_dir>
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI = ROOT / "app/src/main/java/com/omni/llm/ui"

SCREENS = [
    "AgentScreen",
    "ChatScreen",
    "ModelsScreen",
    "SettingsScreen",
    "WelcomeScreen",
]

HEADER = """package com.omni.llm.ui

import androidx.compose.runtime.Composable
import com.omni.llm.agent.AgentEngine
import com.omni.llm.data.ModelEntry
import com.omni.llm.data.ProjectFile
import java.io.File

// GENERATED by tools/gen_screen_stubs.py — do not edit.
// Signatures are copied verbatim from the real screens so the MainActivity pass cannot drift.
"""

THEME_STUB = """package com.omni.llm.ui.theme

import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color

// GENERATED by tools/gen_screen_stubs.py — do not edit.
// Colour values are read from the real Theme.kt where possible; anything missing is a literal.

@Composable
fun OmniTheme(darkTheme: Boolean = true, content: @Composable () -> Unit) {}
"""



def signature(name: str) -> str | None:
    path = UI / f"{name}.kt"
    if not path.exists():
        return None
    src = path.read_text(encoding="utf-8")
    m = re.search(rf"^fun {name}\((.*?)^\) \{{", src, re.S | re.M)
    if not m:
        return None
    kept = []
    for line in m.group(1).splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith(("//", "*", "/*")):
            continue
        kept.append(line.rstrip())
    return "@Composable fun %s(\n%s\n) {}" % (name, "\n".join(kept))


def palette_stub() -> str:
    """Copy the OmniPalette object out of Theme.kt, minus any @Composable members."""
    path = UI / "theme/Theme.kt"
    if not path.exists():
        return ""
    src = path.read_text(encoding="utf-8")
    m = re.search(r"^object OmniPalette .*?^\}", src, re.S | re.M)
    if not m:
        return ""
    body = m.group(0)
    # Drop @Composable vals, which would need codegen.
    body = re.sub(r"^\s*@Composable\s*$", "", body, flags=re.M)
    # Pull in the private colour constants the palette references (Green, Cyan, ...).
    for const in re.findall(r"^private val (\w+) = (Color\([^)]*\))$", src, flags=re.M):
        body += "\nprivate val %s = %s" % const
    return body


def main() -> int:
    out_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/omni-stubs")
    out_dir.mkdir(parents=True, exist_ok=True)

    parts, missing = [HEADER], []
    for name in SCREENS:
        sig = signature(name)
        if sig is None:
            missing.append(name)
            continue
        parts.append(sig)
    (out_dir / "Screens.kt").write_text("\n\n".join(parts) + "\n", encoding="utf-8")

    (out_dir / "Theme.kt").write_text(THEME_STUB + "\n" + palette_stub() + "\n", encoding="utf-8")
    # No viewModel() shim: lifecycle-viewmodel-compose is on the classpath and already provides it.

    print(f"generated {len(SCREENS) - len(missing)} screen stubs in {out_dir}")
    if missing:
        print("  missing:", ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
